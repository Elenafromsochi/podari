// Rotating non-essential UI copy. Pick a random item per render/session.
// Эти строки НЕ влияют на смысл — только на настроение.

export function pickRandom<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

