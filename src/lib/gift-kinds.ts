export function getKindMeta(id: string | null | undefined): KindMeta | undefined {
  return GIFT_KINDS.find((k) => k.id === id);
}

/** Состояние/износ (звёзды) имеет смысл только для физических вещей.
 *  У услуг, времени и встреч износа нет — оценка идёт по отзывам (звёзды). */
export function hasCondition(id: string | null | undefined): boolean {
  return id === "used_item";
}

export function pickRandomHint(kind: GiftKind): string {
  const meta = getKindMeta(kind);
  const arr = meta?.hints ?? [];
  return arr[Math.floor(Math.random() * arr.length)] ?? "";
}

export function pickRandomSubtitle(kind: GiftKind): string {
  const meta = getKindMeta(kind);
  const arr = meta?.subtitles ?? [];
  return arr[Math.floor(Math.random() * arr.length)] ?? "";
}

